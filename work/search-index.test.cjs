const assert = require('node:assert/strict');
const build = require('./search-index.cjs');
const breeding = require('./data/breeding.json');
const enemyBook = require('./enemy-data/enemies.json');
const itemBook = require('./item-data/catalog.json');
const resourceBook = require('./resource-guides/data.json');
const adventureBook = require('./adventure/data.json');
const details = require('./pal-details/details.json');
const partners = require('./combat-guide/partners.json');
const facilities = require('./facilities/data.json');
const expeditions = require('./expeditions/data.json');
const journals = require('./journals/data.json');
const combat = require('./combat-guide/combat.json');
const humanLinks = require('./human-atlas.cjs')(enemyBook, itemBook, breeding.species, require('./map-data/map-points.json').points);
const rows = build({breeding, enemyBook, itemBook, resourceBook, adventureBook, humanLinks});
const byHref = new Map(rows.map(r => [r.href, r]));
assert.equal(byHref.size, rows.length, 'each deep link is indexed once');
assert.deepEqual(build(), build(), 'deterministic output');
for (const row of rows) {
  assert.equal(typeof row.name, 'string');
  assert(row.name.trim() && row.kind);
  assert.match(row.href, /^#[a-z]+\/[^\s<>"?#]+$/);
  assert(!JSON.stringify(row).includes('data:image'), 'no image payloads');
  if (row.aliases) assert.equal(new Set(row.aliases).size, row.aliases.length);
}
const expectCount = (kind, expected) => assert.equal(rows.filter(r => r.kind === kind).length, expected, kind);
expectCount('帕鲁', breeding.species.length);
expectCount('主动技能', Object.keys(details.moves).length);
expectCount('被动词条', Object.keys(details.passives).length);
expectCount('手术台', Object.values(details.passives).filter(p => p.surgery).length);
expectCount('伙伴技能', breeding.species.filter(p => partners[p.key]).length);
expectCount('物品', itemBook.items.length);
expectCount('设施', facilities.facilities.length);
expectCount('敌人', enemyBook.enemies.length);
expectCount('商人', enemyBook.people.filter(p => p.category === 'merchants').length);
expectCount('中立单位', enemyBook.people.filter(p => p.category !== 'merchants').length);
expectCount('远征', expeditions.stages.length);
expectCount('手记', journals.catalog.length);
expectCount('任务', adventureBook.quests.length);
expectCount('异常状态', combat.status.length);
expectCount('野外采集', resourceBook.gathering.length);
expectCount('据点生产', resourceBook.production.length);
expectCount('探索奖励', adventureBook.chapters.reduce((sum, c) => sum + 1 + c.pools.length, 0));
const pal = byHref.get('#paldex/SheepBall');
assert.equal(pal.name, '棉悠悠');
assert(pal.aliases.includes('Lamball') && pal.aliases.includes('001') && pal.aliases.includes('绵悠悠'));
const passive = byHref.get('#details/passive/trait/CraftSpeed_up2');
assert.equal(passive.name, '工匠精神');
assert(passive.aliases.includes('Artisan') && passive.aliases.includes('CraftSpeed_up2'));
assert.equal(byHref.get('#details/active/move/AquaJet').name, '水流射击');
assert.equal(byHref.get('#details/partner/SheepBall').name, '茸茸盾牌');
assert.equal(byHref.get('#items/Accessory_TalentChecker').name, '伯乐眼镜');
assert.equal(byHref.get('#merchants/SalesPerson').name, '流浪商人');
assert.equal(byHref.get('#guide/status/burn').name, '点燃');
assert.equal(byHref.get('#guide/journals/Day-xx').name, '漂流者的手记 Day -xx');
const {prepareAtlasSearch}=require('./ui/global-search.js');
const search=prepareAtlasSearch(rows);
assert.equal(search('Lamball','帕鲁')[0].name,'棉悠悠');
assert.equal(search('００１','帕鲁')[0].name,'棉悠悠');
assert.equal(search('  CraftSpeed_up2  ','被动词条')[0].href,passive.href);
assert(search('工匠精神').some(row=>row.kind==='被动词条'));
assert(search('工匠精神').some(row=>row.kind==='手术台'));
assert(search('a').length>80,'wide searches retain every matching entry');
assert(search('工匠精神','物品').every(row=>row.kind==='物品'));
assert.equal(search('工匠精神','帕鲁').length,0);
assert.equal(search('no-such-jade-entry').length,0);
assert.equal(search('').length,0);
console.log('Search index:', rows.length, 'unique deep links; all categories, aliases, stable IDs and compact payloads verified.');
